/**
 * Collects the repository's markdown into a module the app imports.
 *
 * The previous approach read the files at request time, walking up from process.cwd() to
 * find the repository root. That works locally and fails in a serverless bundle: the
 * tracer follows static imports, so it never saw a path built at runtime, and the deployed
 * function shipped with no documents at all — the site rendered its shell and listed
 * nothing.
 *
 * Generating at build time keeps the property that mattered — one source of truth, the
 * documentation engineers actually maintain — while removing every runtime assumption
 * about where files live.
 */
import {readFileSync, readdirSync, existsSync, writeFileSync, mkdirSync} from "node:fs";
import {dirname, join, resolve} from "node:path";
import {fileURLToPath} from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..", "..", "..");

if (!existsSync(join(root, "pnpm-workspace.yaml"))) {
  console.error(`[docs] cannot find the repository root from ${here} (looked at ${root})`);
  process.exit(1);
}

/** Root-level documents, in the order a newcomer should meet them. */
const ROOT_DOCS = [
  "README.md", "MAINNET_READINESS.md", "KAURAX_INFRA_AUDIT.md",
  "ARCHITECTURE.md", "DEPLOYMENT.md", "SECURITY.md", "CONTRIBUTING.md",
];

/** Reading order for docs/, rather than whatever the filesystem returns. */
const PREFERRED = [
  "README.md", "architecture.md", "STACK_DECISION.md", "l3.md", "ethereum.md",
  "underlying-l2.md", "sequencer.md", "batcher.md", "settlement.md",
  "data-availability.md", "bridge.md", "key-management.md", "developers.md", "sdk.md",
  "contracts.md", "wallet.md", "ai.md", "validators.md", "security.md",
  "threat-model.md", "decentralization.md", "mainnet-readiness.md",
];

const titleOf = (body, fallback) => {
  const heading = body.split("\n").find((l) => l.startsWith("# "));
  return heading ? heading.replace(/^#\s*/, "").trim() : fallback.replace(/\.md$/, "");
};

const entries = [];

for (const name of ROOT_DOCS) {
  const p = join(root, name);
  if (!existsSync(p)) continue;
  const markdown = readFileSync(p, "utf8");
  // Repository-root files are prefixed. Three of them — README, ARCHITECTURE, SECURITY —
  // share a name with a file in docs/, and those are different documents. The docs/
  // directory is the primary documentation, so it keeps the bare name and these give way.
  //
  // The prefix is a plain word, not a path segment: a slug containing "/" has to be
  // reassembled from a catch-all route and then collides with the app's own basePath,
  // which is exactly the bug this replaced.
  entries.push({
    slug: `repo-${name.replace(/\.md$/, "").toLowerCase().replace(/_/g, "-")}`,
    title: titleOf(markdown, name),
    group: "start",
    markdown,
  });
}

const docsDir = join(root, "docs");
if (existsSync(docsDir)) {
  const present = readdirSync(docsDir).filter((f) => f.endsWith(".md"));
  const ordered = [...PREFERRED.filter((f) => present.includes(f)), ...present.filter((f) => !PREFERRED.includes(f))];
  for (const name of ordered) {
    const markdown = readFileSync(join(docsDir, name), "utf8");
    // Bare name, no prefix. basePath already puts every one of these under /docs, and
    // adding it to the slug as well produced /docs/docs/<name> — or, with a raw anchor,
    // a link to /docs/<name> that the app then resolved as slug "<name>" and could not
    // find. Underscores are left alone: DATA_AVAILABILITY.md and data-availability.md are
    // separate files, and normalising would collapse them onto each other.
    entries.push({
      slug: name.replace(/\.md$/, "").toLowerCase(),
      title: titleOf(markdown, name),
      group: "protocol",
      markdown,
    });
  }
}

if (entries.length === 0) {
  // Failing the build is the point: a docs site with no documents should never deploy.
  console.error("[docs] no markdown found — refusing to generate an empty documentation site");
  process.exit(1);
}

const out = join(here, "..", "lib", "docs-content.ts");
mkdirSync(dirname(out), {recursive: true});
writeFileSync(
  out,
  `// GENERATED by scripts/collect-docs.mjs — do not edit.\n` +
    `// Source: the repository's own markdown. Regenerated on every build.\n` +
    `export interface DocContent {slug: string; title: string; group: "start" | "protocol"; markdown: string}\n` +
    `export const DOCS: DocContent[] = ${JSON.stringify(entries, null, 0)};\n`,
);

console.log(`[docs] collected ${entries.length} documents (${(JSON.stringify(entries).length / 1024).toFixed(0)} KB)`);
