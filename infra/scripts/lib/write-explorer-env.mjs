#!/usr/bin/env node
/**
 * Generate apps/explorer/.env.local from the root .env, copying ONLY the NEXT_PUBLIC_* keys.
 *
 * The explorer must never receive sequencer, batcher, proposer or deployer keys: anything
 * in a NEXT_PUBLIC_ variable is shipped to the browser, and anything else in that file is
 * one careless `process.env` away from being.
 */
import {readFileSync, writeFileSync, existsSync} from "node:fs";
import {resolve, dirname} from "node:path";
import {fileURLToPath} from "node:url";

/** Walk upward to the repository root so this helper can be moved without breaking. */
function repoRoot() {
  let dir = dirname(fileURLToPath(import.meta.url));
  for (let i = 0; i < 12; i++) {
    if (existsSync(resolve(dir, "pnpm-workspace.yaml"))) return dir;
    const parent = dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  throw new Error("could not locate the KAURAX repository root");
}

const root = repoRoot();
const source = resolve(root, ".env");
const target = resolve(root, "apps/explorer/.env.local");

if (!existsSync(source)) {
  console.error("write-explorer-env: .env does not exist");
  process.exit(1);
}

const kept = readFileSync(source, "utf8")
  .split("\n")
  .filter((line) => /^NEXT_PUBLIC_[A-Z0-9_]+=/.test(line));

writeFileSync(
  target,
  [
    "# Generated by scripts/lib/write-explorer-env.mjs — do not edit by hand.",
    "# Only NEXT_PUBLIC_* keys are copied. Secrets never reach the explorer.",
    ...kept,
    "",
  ].join("\n"),
);

console.log(`    wrote ${kept.length} public variables to apps/explorer/.env.local`);
